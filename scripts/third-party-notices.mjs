// Generates THIRD_PARTY_NOTICES.md: license texts for every npm package and Rust
// crate that ships inside the macOS app. Run `npm run notices` after changing
// dependencies; CI checks that the committed file is current.
import { execFileSync } from 'node:child_process';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';

const root = join(dirname(new URL(import.meta.url).pathname), '..');
const LICENSE_FILE =
  /^(licen[cs]e|copying|notice|ofl)([-._].*)?(\.(md|txt))?$/i;

function licenseTexts(dir) {
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => LICENSE_FILE.test(name))
    .sort()
    .map((name) => readFileSync(join(dir, name), 'utf8').trim())
    .filter(Boolean);
}

// npm: production dependencies from the lockfile.
const lock = JSON.parse(readFileSync(join(root, 'package-lock.json'), 'utf8'));
const npm = Object.entries(lock.packages)
  .filter(([path, meta]) => path && !meta.dev)
  .map(([path, meta]) => {
    const dir = join(root, path);
    const pkg = JSON.parse(readFileSync(join(dir, 'package.json'), 'utf8'));
    return {
      name: pkg.name,
      version: pkg.version,
      license: meta.license ?? pkg.license ?? 'UNKNOWN',
      source:
        typeof pkg.repository === 'string'
          ? pkg.repository
          : (pkg.repository?.url ??
            `https://www.npmjs.com/package/${pkg.name}`),
      texts: licenseTexts(dir),
    };
  });

// Rust: crates linked into the aarch64 macOS app (normal dependencies only).
const metadata = JSON.parse(
  execFileSync(
    'cargo',
    [
      'metadata',
      '--format-version',
      '1',
      '--locked',
      '--filter-platform',
      'aarch64-apple-darwin',
      '--manifest-path',
      join(root, 'src-tauri/Cargo.toml'),
    ],
    { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 },
  ),
);
const packages = new Map(metadata.packages.map((p) => [p.id, p]));
const nodes = new Map(metadata.resolve.nodes.map((n) => [n.id, n]));
const shipped = new Set();
const queue = [metadata.resolve.root];
while (queue.length) {
  const id = queue.pop();
  if (shipped.has(id)) continue;
  shipped.add(id);
  for (const dep of nodes.get(id)?.deps ?? [])
    if (dep.dep_kinds.some((kind) => kind.kind === null)) queue.push(dep.pkg);
}
const rust = [...shipped]
  .map((id) => packages.get(id))
  .filter((p) => p && p.name !== 'bindaas')
  .map((p) => ({
    name: p.name,
    version: p.version,
    license: p.license ?? (p.license_file ? 'See license file' : 'UNKNOWN'),
    source: p.repository ?? `https://crates.io/crates/${p.name}`,
    texts: licenseTexts(dirname(p.manifest_path)),
  }));

const all = [...npm, ...rust].sort(
  (a, b) => a.name.localeCompare(b.name) || a.version.localeCompare(b.version),
);
const missing = all.filter((p) => !p.texts.length);
// Many packages share identical license texts; print each distinct text once.
const texts = new Map();
for (const p of all)
  p.refs = p.texts.map((text) => {
    if (!texts.has(text)) texts.set(text, texts.size + 1);
    return texts.get(text);
  });
// Packages published without a license file reference the standard text of their
// declared license, taken from another package that ships it verbatim.
const standard = {
  'Apache-2.0': (t) => /Apache License\s+Version 2\.0, January 2004/.test(t),
  'MPL-2.0': (t) => /Mozilla Public License Version 2\.0/.test(t),
  'BSD-3-Clause': (t) =>
    /Neither the name/.test(t) && /Redistribution and use/.test(t),
  MIT: (t) =>
    /^(MIT License|The MIT License|Copyright)/.test(t) &&
    /Permission is hereby granted/.test(t),
  Zlib: (t) => /This software is provided 'as-is'/.test(t),
};
for (const p of all.filter((p) => !p.refs.length)) {
  for (const id of p.license.split(/\s+OR\s+|\//)) {
    const test = standard[id.trim()];
    const match = test && [...texts].find(([text]) => test(text));
    if (match) {
      p.refs = [match[1]];
      p.standard = true;
      break;
    }
  }
}
const lines = [
  '# Third-party notices',
  '',
  'Bindaas includes the open-source components below. Each is used under its own license. Components under the Mozilla Public License 2.0 are used unmodified; their source code is available at the linked repositories.',
  '',
  `Generated by \`npm run notices\` — ${all.length} components, ${texts.size} distinct license texts.`,
  '',
  '| Component | Version | License | Source | Text |',
  '| --- | --- | --- | --- | --- |',
  ...all.map(
    (p) =>
      `| ${p.name} | ${p.version} | ${p.license} | ${p.source} | ${
        p.refs.length
          ? p.refs.map((n) => `[${n}](#text-${n})`).join(' ') +
            (p.standard ? ' (standard text)' : '')
          : 'see source'
      } |`,
  ),
  '',
  '## License texts',
  '',
];
for (const [text, n] of texts)
  lines.push(
    `<a id="text-${n}"></a>`,
    '',
    `### Text ${n}`,
    '',
    '```text',
    text,
    '```',
    '',
  );
writeFileSync(join(root, 'THIRD_PARTY_NOTICES.md'), lines.join('\n'));
console.log(
  `THIRD_PARTY_NOTICES.md: ${npm.length} npm packages, ${rust.length} Rust crates, ${texts.size} distinct texts, ${missing.length} without a bundled license file.`,
);
